class NetworkMonitor:
    """
    Simulates a ground-based software system for monitoring
    network performance at scale.
    """
    def __init__(self, data_dir="telemetry_vault"):
        self.data_dir = data_dir
        if not os.path.exists(self.data_dir):
            os.makedirs(self.data_dir)

        # Contamination is set to 5% - assuming 5% of traffic has chronic issues
        self.model = IsolationForest(contamination=0.05, random_state=42)
        self.scaler = StandardScaler()

    def generate_synthetic_telemetry(self, num_samples=1000):
        """
        Generates realistic network metrics for Starlink/Direct-to-Cell nodes.
        Features: Latency (ms), Jitter, Packet Loss (%), SNR (Signal-to-Noise)
        """
        print(f"Generating {num_samples} synthetic telemetry records...")
        timestamps = [datetime.now() - timedelta(minutes=i) for i in range(num_samples)]

        latency = np.random.normal(loc=30, scale=5, size=num_samples)
        packet_loss = np.random.exponential(scale=0.1, size=num_samples)
        snr = np.random.normal(loc=15, scale=2, size=num_samples)

        # Inject "Widespread Application Issues" (Anomalies)
        anomaly_indices = np.random.choice(range(num_samples), size=int(num_samples * 0.03), replace=False)
        latency[anomaly_indices] += np.random.uniform(50, 150, size=len(anomaly_indices))
        packet_loss[anomaly_indices] += np.random.uniform(2, 10, size=len(anomaly_indices))
        snr[anomaly_indices] -= np.random.uniform(5, 10, size=len(anomaly_indices))

        df = pd.DataFrame({
            'timestamp': timestamps,
            'latency_ms': latency,
            'packet_loss_pct': packet_loss,
            'snr_db': snr,
            'node_id': np.random.randint(100, 200, size=num_samples)
        })
        return df

    def store_to_parquet(self, df, partition_name="network_logs"):
        """
        Saves data using Parquet format. Demonstrates 'Big Data' handling
        through high-efficiency columnar storage and compression.
        """
        # Partitioning by node_id to simulate TB-scale data organization
        file_path = os.path.join(self.data_dir, f"{partition_name}.parquet")
        table = pa.Table.from_pandas(df)
        pq.write_table(table, file_path, compression='snappy')
        print(f"Stored data to compressed Parquet: {file_path}")
        return file_path

    def train_anomaly_detector(self, file_path):
        """
        Reads historical Parquet data and trains the Isolation Forest model.
        """
        print("Loading historical Parquet data for model training...")
        df = pd.read_parquet(file_path)

        features = ['latency_ms', 'packet_loss_pct', 'snr_db']
        X = df[features]

        X_scaled = self.scaler.fit_transform(X)
        self.model.fit(X_scaled)
        print("Anomaly detection model trained successfully.")

    def detect_outages(self, new_data_df):
        """
        Predicts if current network metrics indicate a widespread issue.
        Returns: DataFrame with an 'is_anomaly' flag.
        """
        features = ['latency_ms', 'packet_loss_pct', 'snr_db']
        X_new = self.scaler.transform(new_data_df[features])

        predictions = self.model.predict(X_new)
        new_data_df['is_anomaly'] = [True if p == -1 else False for p in predictions]

        anomalies_found = new_data_df[new_data_df['is_anomaly']]
        print(f"Analysis Complete: Detected {len(anomalies_found)} potential network issues.")
        return new_data_df

